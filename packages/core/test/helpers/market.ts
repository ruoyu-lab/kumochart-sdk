export function btcusdtHours(): BarInput[] {
  return BTCUSDT_1H.trim()
    .split('\n')
    .map((line) => {
      const [time, open, high, low, close, volume] = line.split(',').map(Number) as [
        number,
        number,
        number,
        number,
        number,
        number
      ];
      return { time, open, high, low, close, volume };
    });
}

/**
 * Real bars of BTCUSDT on Binance spot, from Binance's public market data
 * (`data-api.binance.vision`, `/api/v3/klines`): 400 daily bars to 21 October 2026 and 2000 hourly
 * bars to the end of that day, all closed. Rows are `[time in seconds, open, high, low, close,
 * volume]`.
 */
export const BTCUSDT = { '1d': barsOf(daily), '1h': barsOf(hourly) } as const;

function barsOf(rows: readonly (readonly number[])[]): Bar[] {
  return rows.map(([time = 0, open = 0, high = 0, low = 0, close = 0, volume = 0]) => ({
    time: time * 1000,
    open,
    high,
    low,
    close,
    volume
  }));
}
